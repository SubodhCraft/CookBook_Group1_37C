    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        // TODO add your handling code here:
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this recipe?",
        "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        boolean deleted = recipeDAO.deleteRecipe(currentRecipeId);

        if (deleted) {
            javax.swing.JOptionPane.showMessageDialog(this, "Recipe deleted successfully.");
            controller.loadRecipesToHome(); // Refresh home
            controller.loadBookmarkedRecipes(); // Refresh bookmarks
             // Reload homepage recipes and bookmarks
            

            // Close the dialog if it was opened inside a JDialog
            java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(this);
            if (window instanceof javax.swing.JDialog) {
                window.dispose();
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to delete recipe.");
        }
    }
    }//GEN-LAST:event_deleteButtonActionPerformed

