    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        // TODO add your handling code here:
          Recipe recipe = controller.getRecipeById(currentRecipeId);
    if (recipe != null) {
        // Load data into update panel fields
        updatePanel.loadRecipeData(recipe);

        // Switch to update panel in CardLayout
        java.awt.CardLayout cl = (java.awt.CardLayout)(mainPanel.getLayout());
        cl.show(mainPanel, "update");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Recipe data not found.");
    }
        java.awt.Window window = javax.swing.SwingUtilities.getWindowAncestor(this);
    if (window instanceof javax.swing.JDialog) {
        window.dispose();
    }

    }//GEN-LAST:event_updateButtonActionPerformed


