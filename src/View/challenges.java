    private void StartbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_StartbtnActionPerformed
        // TODO add your handling code here:
if (!isRunning) {
    time = 1 * 60;
    isRunning = true;
    currentChallengeReward = 10;

    timer = new Timer(1000, new ActionListener() {
        public void actionPerformed(ActionEvent e) {
            int minutes = time / 60;
            int seconds = time % 60;
            time_label.setText(String.format("%02d:%02d", minutes, seconds));
            time--;

             if (time < 0) {
                    timer.stop();
                    isRunning = false;

                    // Add reward points
                    rewardPoints += currentChallengeReward;
                    Reward.setText("Reward: " + rewardPoints);

                    // Show message
                    JOptionPane.showMessageDialog(null,currentChallengeReward + " points!");
                }
       

        }
    });
    timer.start();
}


    }//GEN-LAST:event_StartbtnActionPerformed

