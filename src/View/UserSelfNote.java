    private void addNoteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addNoteButtonActionPerformed
        // TODO add your handling code here:
        JTextField titleField = new JTextField(20);
JTextArea descArea = new JTextArea(5, 20);
descArea.setLineWrap(true);
descArea.setWrapStyleWord(true);
JScrollPane areaScrollPane = new JScrollPane(descArea);

JPanel inputPanel = new JPanel(new BorderLayout());
inputPanel.add(new JLabel("Title:"), BorderLayout.NORTH);
inputPanel.add(titleField, BorderLayout.CENTER);
inputPanel.add(new JLabel("Description:"), BorderLayout.SOUTH);

JPanel finalPanel = new JPanel(new BorderLayout());
finalPanel.add(inputPanel, BorderLayout.NORTH);
finalPanel.add(areaScrollPane, BorderLayout.CENTER);

int result = JOptionPane.showConfirmDialog(
    this, finalPanel, "Add Note", JOptionPane.OK_CANCEL_OPTION);

if (result == JOptionPane.OK_OPTION) {
    String title = titleField.getText().trim();
    String desc = descArea.getText().trim();
    if (emptyLabel.isVisible()) {
    emptyLabel.setVisible(false);
}
    if (!title.isEmpty() && !desc.isEmpty()) {
        addStickyNote(title, desc);
    }
}
}
private void addStickyNote(String title, String description) {
    //notepanel.setPreferredSize(new Dimension(200, 150)); // fixed note size
    
    JPanel notePanel = new JPanel(new BorderLayout());
    notePanel.setPreferredSize(new Dimension(200, 150));
    notePanel.setBorder(BorderFactory.createLineBorder(new Color(127, 1, 31), 2));
    notePanel.setBackground(new Color(255, 223, 223)); // Sticky note yellow
    notesScrollPane.setVerticalScrollBarPolicy(JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED);
    notesPanel.setPreferredSize(new Dimension(840, 1000)); // enough height to scroll



    JLabel titleLabel = new JLabel("<html><b>" + title + "</b></html>");
    JTextArea descArea = new JTextArea(description);
    descArea.setEditable(false);
    descArea.setLineWrap(true);
    descArea.setWrapStyleWord(true);
    descArea.setOpaque(false);

    JScrollPane descScroll = new JScrollPane(descArea);
    descScroll.setBorder(null);

    JPanel buttonPanel = new JPanel(new FlowLayout(FlowLayout.RIGHT, 5, 2));
    JButton editBtn = new JButton("Edit");
    JButton deleteBtn = new JButton("Delete");

    // DELETE button
    deleteBtn.addActionListener(e -> {
        notesPanel.remove(notePanel);
        notesPanel.revalidate();
        notesPanel.repaint();
        if (notesPanel.getComponentCount() == 1) {
    emptyLabel.setVisible(true); 
        }
    });

    // EDIT button
    editBtn.addActionListener(e -> {
        String newTitle = JOptionPane.showInputDialog(this, "Edit Title:", title);
        
   
      
        //ImageIcon icon = new ImageIcon("View/edit-2 1.png");
         //JLabel imageLabel = new JLabel(icon);
         
        JTextArea editArea = new JTextArea(description, 5, 20);
        JScrollPane editScroll = new JScrollPane(editArea);
        int result = JOptionPane.showConfirmDialog(this, editScroll, "Edit Description", JOptionPane.OK_CANCEL_OPTION);
        if (result == JOptionPane.OK_OPTION) {
            titleLabel.setText("<html><b>" + newTitle + "</b></html>");
            descArea.setText(editArea.getText());
        }
    });

    buttonPanel.add(editBtn);
    buttonPanel.add(deleteBtn);

    notePanel.add(titleLabel, BorderLayout.NORTH);
    notePanel.add(descScroll, BorderLayout.CENTER);
    notePanel.add(buttonPanel, BorderLayout.SOUTH);

    notesPanel.add(notePanel);
    notesPanel.revalidate();
    notesPanel.repaint();
    if (notesPanel.getComponentCount() == 1) {
    emptyLabel.setVisible(true); 
    }

    }//GEN-LAST:event_addNoteButtonActionPerformed

